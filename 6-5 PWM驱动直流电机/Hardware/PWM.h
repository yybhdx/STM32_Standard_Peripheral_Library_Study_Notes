#ifndef __PWM_H
#define __PWM_H

/**
  * @摘要    PWM初始化函数
  * @说明    配置TIM2通道3输出PWM信号，频率1kHz，初始占空比0%
  */
void PWM_Init(void);

/**
  * @摘要    设置PWM占空比（修改TIM2通道3的CCR值）
  * @参数    Compare: CCR值，范围：0~100，对应占空比0%~100%
  */
void PWM_SetCompare3(uint16_t Compare);

#endif
